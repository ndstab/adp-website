// Lists every review marker in /content so nothing unverified ships by accident.
//   npm run review               print the report
//   npm run review -- --write    also save it to docs/REVIEW-ITEMS.md
//
// Markers: "[ADD]" (information ADP must supply), "[CONFIRM ...]" (an assumption to confirm),
// "verify": true on a field, and <Verify /> inside insight MDX (claims pending a source check).
import {readFileSync, readdirSync, statSync, writeFileSync} from 'node:fs';
import {join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const contentDir = join(root, 'content');

function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? files(path) : [path];
  });
}

const found = {add: [], confirm: [], verify: []};

function walk(value, path, file) {
  if (typeof value === 'string') {
    if (value.includes('[ADD]')) found.add.push({file, path, text: value});
    const confirm = value.match(/\[CONFIRM[^\]]*\]/g);
    if (confirm) found.confirm.push({file, path, text: confirm.join(' ')});
    if (value.startsWith('[VERIFY]')) found.verify.push({file, path, text: value});
  } else if (Array.isArray(value)) {
    value.forEach((v, i) => walk(v, `${path}[${i}]`, file));
  } else if (value && typeof value === 'object') {
    if (value.verify === true) {
      const label = value.label ?? value.title ?? value.value ?? '';
      found.verify.push({file, path, text: typeof label === 'string' ? label : JSON.stringify(label)});
    }
    for (const [k, v] of Object.entries(value)) walk(v, path ? `${path}.${k}` : k, file);
  }
}

for (const file of files(contentDir)) {
  const rel = relative(root, file);
  if (file.endsWith('.json')) {
    const data = JSON.parse(readFileSync(file, 'utf8'));
    // Solution outcomes are always flagged on the page, so list them explicitly.
    if (Array.isArray(data.outcomes)) data.outcomes.forEach((o, i) => found.verify.push({file: rel, path: `outcomes[${i}]`, text: `${o.value} ${o.label}`}));
    if (data.vision2030?.programs) found.verify.push({file: rel, path: 'vision2030.programs', text: data.vision2030.programs.join(', ')});
    walk(data, '', rel);
  } else if (file.endsWith('.mdx')) {
    readFileSync(file, 'utf8')
      .split('\n')
      .forEach((line, i) => {
        if (line.includes('<Verify')) found.verify.push({file: rel, path: `line ${i + 1}`, text: line.replace(/<Verify \/>/g, '⟨verify⟩').trim().slice(0, 140)});
        if (line.includes('[ADD]')) found.add.push({file: rel, path: `line ${i + 1}`, text: line.trim()});
      });
  }
}

const section = (title, items) =>
  [`## ${title} (${items.length})`, '', ...items.map((i) => `- \`${i.file}\` · ${i.path}: ${i.text.replace(/\s+/g, ' ').slice(0, 160)}`), ''].join('\n');

const report = [
  '# Review items in /content',
  '',
  'Generated by `npm run review`. Do not edit by hand; fix the content and re-run.',
  '',
  section('[ADD]: information to supply', found.add),
  section('[CONFIRM]: assumptions to confirm', found.confirm),
  section('VERIFY: claims to check against a current source', found.verify)
].join('\n');

console.log(report);
if (process.argv.includes('--write')) {
  writeFileSync(join(root, 'docs/REVIEW-ITEMS.md'), report + '\n');
  console.error(`\nWrote docs/REVIEW-ITEMS.md: ${found.add.length} ADD, ${found.confirm.length} CONFIRM, ${found.verify.length} VERIFY`);
}
